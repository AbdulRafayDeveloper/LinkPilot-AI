import type { NextConfig } from "next"
import { APP_VERSION_HEADER } from "./src/constants/appVersion"

const isProduction = process.env.NODE_ENV === "production"

/**
 * Which build this is, so a tab left open across a deploy can tell it is running old code
 * (lib/appVersion.ts). Vercel's deployment id is the same in every process of one build, and a
 * redeploy of the same commit gets a new one. Off Vercel the id is made once and put in the
 * environment, because Next loads this file again in its worker processes and they must all agree:
 * a header from one value and a page compiled with another would announce an update for ever.
 */
const APP_BUILD_VERSION = process.env.VERCEL_DEPLOYMENT_ID || (process.env.APP_BUILD_VERSION ||= Date.now().toString(36))

// Every brand icon in public/ (generated by `npm run brand:icons`); their names aren't fingerprinted,
// so they're cached for a week and revalidated in the background rather than forever
const BRAND_ASSETS =
  "/:asset(favicon\\.ico|favicon(?:-\\d+x\\d+)?\\.png|apple-touch-icon(?:-\\d+x\\d+)?\\.png|icon-\\d+x\\d+\\.png|maskable-icon(?:-\\d+x\\d+)?\\.png|monochrome-icon\\.png|safari-pinned-tab\\.svg|linkpilot-mark\\.(?:png|svg))"

const SECURITY_HEADERS = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  // Prompt Creator records the spoken description in the page itself, so the microphone is allowed for this origin only
  { key: "Permissions-Policy", value: "camera=(), microphone=(self), geolocation=(), browsing-topics=()" },
  // No other site may frame the app (clickjacking)
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Content-Security-Policy", value: "frame-ancestors 'none'" },
  // HTTPS only once deployed; on local http it would do nothing useful
  ...(isProduction ? [{ key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" }] : []),
]

const nextConfig: NextConfig = {
  // No "X-Powered-By: Next.js" on responses
  poweredByHeader: false,
  // Files read from disk at runtime ship with the routes that read them: the fonts and the logo
  // for the social preview cards (prompts and data all live in MongoDB)
  outputFileTracingIncludes: {
    "/og/**/*": ["./src/assets/fonts/**/*", "./public/icon-256x256.png"],
  },
  // The dev-only Next.js badge would sit on the sidebar's pinned Global AI Prompts item
  devIndicators: { position: "bottom-right" },
  // Compiled into the browser code as a constant, so the page knows the build it was served from
  env: { APP_BUILD_VERSION },
  async headers() {
    return [
      // Every answer says which build sent it; the page compares that with its own (lib/appVersion.ts)
      { source: "/:path*", headers: [...SECURITY_HEADERS, { key: APP_VERSION_HEADER, value: APP_BUILD_VERSION }] },
      { source: BRAND_ASSETS, headers: [{ key: "Cache-Control", value: "public, max-age=604800, stale-while-revalidate=86400" }] },
      // The browser checks for a new service worker on every visit, and it may control the whole site
      {
        source: "/sw.js",
        headers: [
          { key: "Cache-Control", value: "no-cache, no-store, must-revalidate" },
          { key: "Service-Worker-Allowed", value: "/" },
        ],
      },
    ]
  },
  /**
   * Important Files became Personal Drive at /personal-drive. The old address still opens it, as a
   * **307**, never a permanent redirect: a browser keeps a permanent one for good and would follow
   * it without asking the server again, which is exactly what made the root redirect a problem.
   */
  async redirects() {
    return [{ source: "/important-files", destination: "/personal-drive", permanent: false }]
  },
  // The manifest is app/manifest.ts (/manifest.webmanifest); tools that look for the other common names find it too
  async rewrites() {
    return [
      { source: "/manifest.json", destination: "/manifest.webmanifest" },
      { source: "/site.webmanifest", destination: "/manifest.webmanifest" },
    ]
  },
}

export default nextConfig;
